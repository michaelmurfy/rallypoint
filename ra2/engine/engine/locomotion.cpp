LocoKind loco_kind_from_clsid(const char* clsid, bool is_infantry) {
    char buf[10] = {};
    std::size_t n = 0;
    for (const char* p = clsid ? clsid : ""; *p && n < 9; ++p) {
        if (*p == ' ' || *p == '\t') { if (n == 0) continue; break; }
        buf[n++] = static_cast<char>(std::toupper(static_cast<unsigned char>(*p)));
    }
    if (n == 0) return is_infantry ? LocoKind::Walk : LocoKind::Drive;
    if (std::strncmp(buf, "{4A582741", 9) == 0) return LocoKind::Drive;
    if (std::strncmp(buf, "{4A582742", 9) == 0) return LocoKind::Hover;
    if (std::strncmp(buf, "{4A582744", 9) == 0) return LocoKind::Walk;
    if (std::strncmp(buf, "{4A582746", 9) == 0) return LocoKind::Fly;
    if (std::strncmp(buf, "{4A582747", 9) == 0) return LocoKind::Teleport;
    if (std::strncmp(buf, "{2BEA74E1", 9) == 0) return LocoKind::Ship;
    if (std::strncmp(buf, "{92612C46", 9) == 0) return LocoKind::Jumpjet;
    return LocoKind::Other;
}

const RawTrack& raw_track(int id) {
    if (id < 0 || id > 15) id = 0;
    return kRaw[id];
}

const TurnTrack& turn_track(int cur_dir, int next_dir) {
    return kTurn[((cur_dir & 7) << 3) | (next_dir & 7)];
}

void track_point(int id, int idx, int flags, int& x, int& y, int& facing_u16) {
    const RawTrack& t = raw_track(id);
    if (idx < 0 || idx >= t.n) {
        x = y = 0;
        facing_u16 = 0;
        return;
    }
    int px = t.pts[idx].x, py = t.pts[idx].y, f = t.pts[idx].facing;
    // [RE: FUN_004B46A0] swap, then negate x, then negate y; the facing is
    // mirrored the same way (swap: 192 - f, -x: -f, -y: 128 - f, mod 256).
    if (flags & 1) { const int s = px; px = py; py = s; f = 192 - f; }
    if (flags & 2) { px = -px; f = -f; }
    if (flags & 4) { py = -py; f = 128 - f; }
    x = px;
    y = py;
    facing_u16 = (f & 0xFF) << 8;
}

int dir8_of_step(int dx, int dy) {
    static const int kDir[3][3] = {{7, 0, 1}, {6, -1, 2}, {5, 4, 3}};   // [dy+1][dx+1]
    if (dx < -1 || dx > 1 || dy < -1 || dy > 1) return -1;
    return kDir[dy + 1][dx + 1];
}

int leptons_per_frame(double speed_cps) {
    if (speed_cps <= 0.0) return 0;
    // speed_cps = lept * 15 / 256 exactly for a type's Speed=; the epsilon
    // absorbs the double round trip.
    return om::ftol(speed_cps * 256.0 / 15.0 + 1e-6);
}

int apply_speed_pct(int speed, double pct) {
    return om::ftol(static_cast<double>(speed) * pct);
}

int infantry_speed(int s, bool prone, bool crawls) {
    if (!prone) return s;
    return crawls ? s - s / 3 : s + s / 2;
}

double hover_target_fraction(int facing_err_u16, int dist_to_goal_leptons, bool straightaway,
                             double boost) {
    int e = facing_err_u16 < 0 ? -facing_err_u16 : facing_err_u16;
    if (e > 0x2000) return 0.0;
    double t = dist_to_goal_leptons <= 0x100 ? 0.5 : 1.0;
    if (straightaway) t *= boost;
    return t > 1.0 ? 1.0 : t;
}

double hover_ramp(double cur, double target, double accel, double brake) {
    if (cur < target) {
        cur += accel > 0.0 ? 1.0 / (accel * 900.0) : 1.0;
        if (cur > target) cur = target;
    } else if (cur > target) {
        cur -= brake > 0.0 ? 1.0 / (brake * 900.0) : 1.0;
        if (cur < target) cur = target;
    }
    return cur;
}

